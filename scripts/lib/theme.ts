// Tailwind v4 theme of the site, generated from docs/design/tokens.json (DECISOES § 41).
// Pure: scripts/design/tema.ts writes src/styles/theme.css and tests/unit/theme.test.ts keeps it fresh.
// `@theme reference inline` emits no :root variables and makes utilities read var(--token) directly,
// so the values that switch between themes stay in docs/design/tokens.css and a name that equals its
// own variable (--radius-xl: var(--radius-xl)) cannot become a cycle.

export const THEME_HEADER = '/* Generated by scripts/design/tema.ts from docs/design/tokens.json; do not edit by hand (DECISOES § 41). */';

/** Yellow belongs to the Download button alone: no utility may ever paint it (DECISOES § 18). */
export const YELLOW_COLORS: readonly string[] = ['sun', 'on-sun', 'sun-edge'];
export const YELLOW_SHADOWS: readonly string[] = ['shadow-lip-sun', 'shadow-lip-on-deep'];

function asRecord(value: unknown, where: string): Record<string, unknown> {
  if (typeof value !== 'object' || value === null || Array.isArray(value)) throw new Error(`tokens.json: ${where} deveria ser um objeto`);
  return value as Record<string, unknown>;
}

/** Names of the tokens of one group (`color`, `spacing`, ...), in the order of tokens.json. */
function groupNames(tokens: unknown, group: string): string[] {
  const list = asRecord(asRecord(tokens, 'raiz')[group], group)['tokens'];
  if (!Array.isArray(list)) throw new Error(`tokens.json: ${group}.tokens deveria ser uma lista`);
  return list.map((token, index) => {
    const name = asRecord(token, `${group}.tokens[${index}]`)['name'];
    if (typeof name !== 'string' || !/^[a-z][a-z0-9-]*$/.test(name)) throw new Error(`tokens.json: ${group}.tokens[${index}] sem nome válido`);
    return name;
  });
}

function familyNames(tokens: unknown): string[] {
  const families = asRecord(asRecord(asRecord(tokens, 'raiz')['type'], 'type')['families'], 'type.families');
  return Object.keys(families);
}

function prefixed(names: string[], prefix: string, group: string): string[] {
  for (const name of names) if (!name.startsWith(prefix)) throw new Error(`tokens.json: ${group} "${name}" deveria começar por ${prefix}`);
  return names;
}

/** Every custom property tokens.css defines for the design system, without the leading `--`. */
export function tokenNames(tokens: unknown): string[] {
  return [
    ...groupNames(tokens, 'color'),
    ...groupNames(tokens, 'spacing'),
    ...groupNames(tokens, 'radius'),
    ...groupNames(tokens, 'shadow'),
    ...groupNames(tokens, 'stroke'),
    ...groupNames(tokens, 'size'),
    ...groupNames(tokens, 'duration'),
    ...groupNames(tokens, 'easing'),
    ...familyNames(tokens).map((family) => `font-${family}`),
  ];
}

/** The full text of src/styles/theme.css. */
export function renderTheme(tokens: unknown): string {
  const colors = groupNames(tokens, 'color').filter((name) => !YELLOW_COLORS.includes(name));
  const spacing = prefixed(groupNames(tokens, 'spacing'), 'space-', 'spacing');
  const radius = prefixed(groupNames(tokens, 'radius'), 'radius-', 'radius');
  const shadows = prefixed(groupNames(tokens, 'shadow'), 'shadow-', 'shadow').filter((name) => !YELLOW_SHADOWS.includes(name));
  const fonts = familyNames(tokens);
  const easings = groupNames(tokens, 'easing').filter((name) => name.startsWith('ease-'));
  const lines = [
    ...colors.map((name) => `--color-${name}: var(--${name});`),
    ...spacing.map((name) => `--spacing-${name.slice('space-'.length)}: var(--${name});`),
    ...radius.map((name) => `--${name}: var(--${name});`),
    ...shadows.map((name) => `--${name}: var(--${name});`),
    ...fonts.map((family) => `--font-${family}: var(--font-${family});`),
    ...easings.map((name) => `--${name}: var(--${name});`),
  ];
  return `${THEME_HEADER}\n@theme reference inline {\n  --*: initial;\n${lines.map((line) => `  ${line}\n`).join('')}}\n`;
}
